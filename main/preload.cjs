const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listSongs: () => ipcRenderer.invoke('songs:list'),
  openLibrarySong: (name) => ipcRenderer.invoke('songs:open', name),
  updateSongInfo: (name, library) => ipcRenderer.invoke('songs:info', name, library),
  saveMidi: (file) => ipcRenderer.invoke('midi:save', file),
  beginStems: (names) => ipcRenderer.invoke('stems:begin', names),
  appendStem: (id, name, bytes) => ipcRenderer.invoke('stems:chunk', id, name, bytes),
  finishStems: (id) => ipcRenderer.invoke('stems:finish', id),
  abortStems: (id) => ipcRenderer.invoke('stems:abort', id),
  beginPreview: (meta) => ipcRenderer.invoke('preview:begin', meta),
  appendPreview: (id, part, start, channels) => ipcRenderer.invoke('preview:chunk', id, part, start, channels),
  finishPreview: (id, meta) => ipcRenderer.invoke('preview:finish', id, meta),
  readPreview: (id, start, count, mix, part) => ipcRenderer.invoke('preview:read', id, start, count, mix, part),
  releasePreview: (id) => ipcRenderer.invoke('preview:release', id),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (ui) => ipcRenderer.invoke('settings:save', ui),
  pianoSamples: (notes, id) => ipcRenderer.invoke('piano:samples', notes, id),
  scanBanks: () => ipcRenderer.invoke('banks:scan'),
  aboutInfo: () => ipcRenderer.invoke('about:info'),
  openLink: (url) => ipcRenderer.invoke('link:open', url),
  saveSong: (file) => ipcRenderer.invoke('song:save', file),
  openSong: () => ipcRenderer.invoke('song:open'),
  soundsDir: () => ipcRenderer.invoke('paths:sounds'),
  openInExplorer: (folder) => ipcRenderer.invoke('folder:open', folder),
  fileExists: (folder, name) => ipcRenderer.invoke('file:exists', folder, name),
  beginWav: (folder, name) => ipcRenderer.invoke('wav:begin', folder, name),
  appendWav: (id, bytes) => ipcRenderer.invoke('wav:chunk', id, bytes),
  finishWav: (id) => ipcRenderer.invoke('wav:finish', id),
  abortWav: (id) => ipcRenderer.invoke('wav:abort', id),
});
